import { chromium } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const baseURL = process.env.ESR_TEST_URL || 'http://127.0.0.1:8788';
await fs.mkdir('.qa', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, reducedMotion:'reduce' });
  const page = await context.newPage();
  const errors = [];
  const remote = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith(baseURL)) remote.push(new URL(request.url()).origin); });
  await page.goto(baseURL);
  await page.locator('#totalProjects').filter({hasText:'41'}).waitFor();
  assert.equal(await page.locator('#completedCount').textContent(), '18');
  assert.equal(await page.locator('#addProjectBtn').isVisible(),false);
  await page.screenshot({ path:'.qa/dashboard-desktop.png',fullPage:false });
  await page.locator('#openPresentationMode').click();
  await page.locator('#presentationNextBtn').click();
  await page.locator('.focusNotesBtn').waitFor();
  assert.equal(await page.locator('.presentationProjectNumber').evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 24,true);
  assert.equal(await page.locator('.presentationBadgeRow .badgeSales').evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 21,true);
  const sizing = await page.locator('.presentationDescription').evaluate(el => ({ overflow:getComputedStyle(el).overflowY,height:el.clientHeight,scroll:el.scrollHeight }));
  assert.equal(sizing.overflow,'visible');
  assert.ok(Math.abs(sizing.height - sizing.scroll) <= 2);
  await page.screenshot({path:'.qa/presentation-desktop.png'});
  await page.locator('#toggleBrowserFullscreen').click();
  await page.waitForFunction(() => !!document.fullscreenElement);
  assert.equal(await page.locator('.presentationProjectNumber').evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 24,true);
  assert.equal(await page.locator('.presentationBadgeRow .badgeSales').evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 21,true);
  assert.equal(await page.locator('.presentationDescription').evaluate(el => getComputedStyle(el).overflowY),'visible');
  await page.screenshot({path:'.qa/presentation-fullscreen.png'});
  await page.locator('#toggleBrowserFullscreen').click();
  await page.waitForFunction(() => !document.fullscreenElement);
  await page.locator('.focusNotesBtn').click();
  assert.equal(await page.locator('.presentationStage').evaluate(el => el.classList.contains('notesFocused')),true);
  assert.equal(await page.locator('.presentationMetaGrid').isVisible(),false);
  await page.screenshot({path:'.qa/presentation-comments.png'});
  await page.locator('.focusNotesBtn').click();
  assert.equal(await page.locator('.presentationMetaGrid').isVisible(),true);
  await page.locator('#closePresentationMode').click();
  await page.locator('#themeToggleBtn').click();
  await page.screenshot({path:'.qa/dashboard-light.png'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  for (const width of [768,390]) {
    await page.setViewportSize({width,height:900});
    await page.screenshot({path:`.qa/dashboard-${width}.png`});
    const fits = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1);
    if (!fits) console.log(await page.evaluate(() => { let el=document.querySelector('.chartRow');const list=[];while(el){const c=getComputedStyle(el);list.push({tag:el.tagName,class:el.className,width:c.width,minWidth:c.minWidth,maxWidth:c.maxWidth,display:c.display,grid:c.gridTemplateColumns,box:c.boxSizing});el=el.parentElement;}return list;}));
    assert.ok(fits,`Dashboard fits ${width}px`);
    await page.locator('#openPresentationMode').click();
    await page.locator('#presentationNextBtn').click();
    await page.locator('.focusNotesBtn').waitFor();
    await page.screenshot({path:`.qa/presentation-${width}.png`});
    await page.locator('#closePresentationMode').click();
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(baseURL + '/esr.html');
  const release=`Ship To Name: Sample Transit\n123 Main Street\nHouston, TX 77001\nUSA\nJob Order #:\nRelease Status:\n2_3055\nRELEASED\nVoltage:\n480 VAC\nContact: RELEASED\njane@example.com\nJANE SMITH\nPhone: 713-555-0123`;
  const quote=`Order Contract\nQuotation Number:\nQuotation Date:\n2_3056\nPrepared for:\nJane Smith\njane@example.com\n713-555-0123\nModel Number:\nVoltage: 208 VOLT\nSold To: Ship To:\nSample Transit\n123 Main Street\nHouston, TX 77001\nDescription\nEquipment`;
  for (const [name,fixture,number] of [['release',release,'2_3055'],['quote',quote,'2_3056']]) {
    const doc=await PDFDocument.create();
    const first=doc.addPage();
    fixture.split('\n').forEach((line,i)=>first.drawText(line,{x:40,y:790-i*20,size:11}));
    doc.addPage().drawText('Voltage: 240 VAC Contact: WRONG PERSON',{x:40,y:700});
    await page.locator('#releasePdf').setInputFiles({name:`${name}.pdf`,mimeType:'application/pdf',buffer:Buffer.from(await doc.save())});
    await page.waitForFunction(number => document.querySelector('#jo_job_number').value===number,number);
    assert.equal(await page.locator('#jo_job_name').inputValue(),'Sample Transit');
    assert.equal(await page.locator('#jo_contact_email').inputValue(),'jane@example.com');
    assert.equal(await page.locator('#jo_voltage').inputValue(),name==='release'?'480V - 3 Phase':'208V - 3 Phase');
  }
  await page.screenshot({path:'.qa/pdf-autofill.png'});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#esrForm button[type="submit"]').click();
  const download=await downloadPromise;
  const generated=await PDFDocument.load(await fs.readFile(await download.path()));
  assert.equal(generated.getForm().getTextField('Text1').getText(),'2_3056');
  assert.equal(generated.getForm().getTextField('Text6').getText(),'208V - 3 Phase');
  await page.locator('#releasePdf').setInputFiles({name:'invalid.pdf',mimeType:'application/pdf',buffer:Buffer.from('invalid PDF')});
  await page.locator('#joStatus').filter({hasText:'JO parse failed'}).waitFor();
  assert.equal(await page.locator('#jo_job_number').inputValue(),'2_3056');
  assert.deepEqual(errors,[]);
  assert.deepEqual(remote,[]);
  console.log('Browser checks passed: 59 migrated records; public read-only dashboard; desktop/tablet/phone layouts; large presentation text; expandable natural-height comments; both PDF types; downloaded ESR fields; failed PDF preserves edits; no external runtime requests.');
} finally { await browser.close(); }
